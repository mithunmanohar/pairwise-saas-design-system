#!/usr/bin/env node
// Builds the two "how do I use this?" outputs from the component cards (design-system/components/<Name>/):
//   design-system/catalogue.html  one page to browse every component: open it straight from disk, no server needed.
//                                 Each card renders lazily in an iframe with the generated preview kit; theme and
//                                 density toggles, search, and each card's README.
//   dist/COMPONENTS.md            every component's README plus its props, in one file that ships with the package,
//                                 so people and AI coding tools in a project can read the docs from node_modules.
// Run after build-preview.mjs. No dependencies.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const DS = join(PKG, "..", "..", "design-system");
const KIT = join(DS, "components");
const GROUPS = ["Foundations", "Actions", "Status", "Forms", "Inputs & navigation", "Feedback", "Overlays", "Data display", "Charts", "Shell"];

const cards = readdirSync(KIT, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(KIT, d.name, "preview.html")))
  .map((d) => {
    const html = readFileSync(join(KIT, d.name, "preview.html"), "utf8");
    const meta = (html.match(/<!--\s*@dsCard([^>]*)-->/) || [, ""])[1];
    const num = (k) => { const m = meta.match(new RegExp(`\\b${k}=(\\d+)`)); return m ? Number(m[1]) : undefined; };
    const readme = existsSync(join(KIT, d.name, "README.md")) ? readFileSync(join(KIT, d.name, "README.md"), "utf8").trim() : "";
    return { name: d.name, group: (meta.match(/group="([^"]+)"/) || [])[1], width: num("width"), height: num("height") ?? 300, html: html.replace(/<!--\s*@dsCard[^>]*-->\s*/, ""), readme };
  })
  .filter((c) => c.group) // the Cover card has no group
  .sort((a, b) => (GROUPS.indexOf(a.group) - GROUPS.indexOf(b.group)) || a.name.localeCompare(b.name));
const unknown = cards.filter((c) => !GROUPS.includes(c.group)).map((c) => `${c.name} (${c.group})`);
if (unknown.length) throw new Error("cards in an unknown group: " + unknown.join(", "));

// Tiny Markdown → HTML for the card READMEs: paragraphs, "- " lists, **bold**, `code`.
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const inline = (s) => esc(s).replace(/`([^`]+)`/g, "<code>$1</code>").replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
function md(src) {
  const out = []; let list = null;
  for (const line of src.split("\n")) {
    if (/^\s*- /.test(line)) { list ??= []; list.push(`<li>${inline(line.replace(/^\s*- /, ""))}</li>`); continue; }
    if (list) { out.push(`<ul>${list.join("")}</ul>`); list = null; }
    if (line.trim()) out.push(`<p>${inline(line)}</p>`);
  }
  if (list) out.push(`<ul>${list.join("")}</ul>`);
  return out.join("\n");
}

// ---------- catalogue.html ----------
const data = cards.map(({ name, group, width, height, html }) => ({ name, group, width, height, html }));
const json = JSON.stringify(data).replace(/</g, "\\u003c"); // safe inside <script>
const nav = GROUPS.filter((g) => cards.some((c) => c.group === g)).map((g) =>
  `<div class="cat-navgroup"><div class="pw-caption pw-muted">${esc(g)}</div>${cards.filter((c) => c.group === g).map((c) => `<a href="#${c.name}" data-name="${c.name.toLowerCase()}">${c.name}</a>`).join("")}</div>`).join("\n");
const sections = cards.map((c) => `<section class="cat-card" id="${c.name}" data-name="${c.name.toLowerCase()}">
<header><h2 class="pw-heading">${c.name}</h2><span class="pw-caption pw-muted">${esc(c.group)}</span></header>
<div class="cat-readme">${md(c.readme)}</div>
<div class="cat-frame" data-card="${c.name}" style="height:${c.height}px"></div>
</section>`).join("\n");

const page = `<!doctype html>
<!-- Generated by packages/ui/scripts/build-catalogue.mjs. Do not edit. -->
<html lang="en" data-theme="light" data-density="compact"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Pairwise components</title>
<link rel="stylesheet" href="tokens.css"><link rel="stylesheet" href="components/bundle.css">
<style>
body { margin: 0; }
.cat { display: grid; grid-template-columns: 220px minmax(0, 1fr); min-height: 100vh; }
.cat-side { position: sticky; top: 0; height: 100vh; overflow: auto; padding: var(--space-4); border-right: 1px solid var(--border); background: var(--surface-raised); box-sizing: border-box; }
.cat-side h1 { margin: 0 0 var(--space-3); }
.cat-side .pw-input { margin-bottom: var(--space-3); box-sizing: border-box; }
.cat-navgroup { display: grid; margin-bottom: var(--space-3); }
.cat-navgroup a { padding: 2px var(--space-2); border-radius: var(--radius-sm); color: var(--ink); text-decoration: none; }
.cat-navgroup a:hover { background: var(--surface-hover); }
.cat-main { padding: var(--space-5); max-width: 1180px; }
.cat-bar { display: flex; flex-wrap: wrap; gap: var(--space-4); align-items: center; justify-content: space-between; margin-bottom: var(--space-5); }
.cat-bar p { margin: 0; max-width: 640px; }
.cat-card { margin-bottom: var(--space-6); }
.cat-card header { display: flex; gap: var(--space-3); align-items: baseline; }
.cat-card h2 { margin: 0; }
.cat-readme { max-width: 760px; color: var(--ink); }
.cat-readme p, .cat-readme ul { margin: var(--space-2) 0; }
.cat-readme code { font-family: var(--font-mono); font-size: 13px; }
.cat-frame { position: relative; margin-top: var(--space-3); overflow: hidden; border: 1px solid var(--border); border-radius: var(--radius-md); background: var(--surface); }
.cat-frame iframe { position: absolute; top: 0; left: 0; border: 0; transform-origin: 0 0; }
.cat-hidden { display: none; }
@media (max-width: 760px) { .cat { grid-template-columns: 1fr; } .cat-side { position: static; height: auto; } }
</style></head>
<body><div class="cat">
<nav class="cat-side" aria-label="Components">
<h1 class="pw-subheading">Pairwise</h1>
<input class="pw-input" type="search" placeholder="Find a component" aria-label="Find a component" id="cat-q">
${nav}
</nav>
<main class="cat-main">
<div class="cat-bar">
<p>Every component in <code class="pw-mono">@pairwise/ui</code>, live. Use these instead of building your own. Setup and rules: <code class="pw-mono">packages/ui/README.md</code> and <code class="pw-mono">design-system/README.md</code>.</p>
<div style="display:flex;gap:var(--space-3)">
<div class="pw-seg" role="radiogroup" aria-label="Theme" id="cat-theme"><button type="button" role="radio" class="pw-seg__b is-on" aria-checked="true" data-v="light">Light</button><button type="button" role="radio" class="pw-seg__b" aria-checked="false" data-v="dark">Dark</button></div>
<div class="pw-seg" role="radiogroup" aria-label="Density" id="cat-density"><button type="button" role="radio" class="pw-seg__b is-on" aria-checked="true" data-v="compact">Compact</button><button type="button" role="radio" class="pw-seg__b" aria-checked="false" data-v="comfortable">Comfortable</button></div>
</div>
</div>
${sections}
</main></div>
<script>
(function () {
  var CARDS = ${json};
  var byName = {}; CARDS.forEach(function (c) { byName[c.name] = c; });
  var state = { theme: "light", density: "compact" };
  function srcdoc(c) {
    // Absolute URLs: the preload scanner fetches these before <base> applies inside srcdoc.
    var u = function (p) { return new URL(p, location.href).href; };
    var head = '<base href="' + u("components/" + c.name + "/") + '">' +
      '<link rel="stylesheet" href="' + u("tokens.css") + '"><link rel="stylesheet" href="' + u("components/bundle.css") + '">' +
      '<script src="' + u("components/lib/react.production.min.js") + '"><\\/script><script src="' + u("components/lib/react-dom.production.min.js") + '"><\\/script><script src="' + u("components/bundle.js") + '"><\\/script>';
    var html = c.html.replace(/<html([^>]*)>/i, '<html$1 data-theme="' + state.theme + '" data-density="' + state.density + '">');
    return /<head[^>]*>/i.test(html) ? html.replace(/<head([^>]*)>/i, '<head$1>' + head) : head + html;
  }
  function fit(box) {
    var c = byName[box.dataset.card], f = box.firstChild; if (!f) return;
    var w = c.width || box.clientWidth, s = Math.min(1, box.clientWidth / w), h = f._h || c.height;
    f.style.width = w + "px"; f.style.height = h + "px"; f.style.transform = s < 1 ? "scale(" + s + ")" : "";
    box.style.height = Math.round(h * s) + "px";
  }
  function load(box) {
    var f = box.firstChild || box.appendChild(document.createElement("iframe"));
    f.title = box.dataset.card + " examples"; f.srcdoc = srcdoc(byName[box.dataset.card]); fit(box);
    // Grow the frame to its content when the browser lets us measure it (it does for files opened from disk in Chrome).
    f.onload = function () {
      try {
        var d = f.contentDocument, c = byName[box.dataset.card];
        var measure = function () { var h = Math.max(c.height, d.documentElement.scrollHeight); if (h !== f._h) { f._h = h; fit(box); } };
        new ResizeObserver(measure).observe(d.body); setTimeout(measure, 300);
      } catch (e) { /* cross-origin in some browsers: keep the card's own height */ }
    };
  }
  var boxes = Array.prototype.slice.call(document.querySelectorAll(".cat-frame"));
  var io = new IntersectionObserver(function (es) { es.forEach(function (e) { if (e.isIntersecting) { load(e.target); io.unobserve(e.target); } }); }, { rootMargin: "800px 0px" });
  boxes.forEach(function (b) { io.observe(b); });
  addEventListener("resize", function () { boxes.forEach(fit); });
  function seg(id, key) {
    var g = document.getElementById(id);
    g.addEventListener("click", function (e) {
      var b = e.target.closest("button"); if (!b) return;
      Array.prototype.forEach.call(g.children, function (x) { var on = x === b; x.classList.toggle("is-on", on); x.setAttribute("aria-checked", String(on)); });
      state[key] = b.dataset.v; document.documentElement.setAttribute("data-" + key, b.dataset.v);
      boxes.forEach(function (box) { if (box.firstChild) load(box); });
    });
  }
  seg("cat-theme", "theme"); seg("cat-density", "density");
  document.getElementById("cat-q").addEventListener("input", function (e) {
    var q = e.target.value.trim().toLowerCase();
    document.querySelectorAll("[data-name]").forEach(function (el) { el.classList.toggle("cat-hidden", !!q && el.dataset.name.indexOf(q) < 0); });
  });
})();
</script>
</body></html>
`;
writeFileSync(join(DS, "catalogue.html"), page);

// ---------- dist/COMPONENTS.md ----------
const types = readFileSync(join(PKG, "src", "types.ts"), "utf8").split("\n");
const propsOf = (name) => types.find((l) => l.startsWith(`export interface ${name}Props `));
const docs = [
  "# @pairwise/ui components",
  "",
  "Generated from the component cards. Use these components for all UI; don't build your own buttons, inputs, tables, menus, modals or toasts, and don't add another UI library.",
  "",
  "Setup: import `@pairwise/ui/fonts.css`, `@pairwise/ui/tokens.css` and `@pairwise/ui/styles.css` once; set `data-theme` (light | dark) and `data-density` (compact | comfortable) on `<html>`; wrap the app in `<PairwiseProvider>`; render `<Toaster />` once if you use `toast()`.",
  "",
  "Styling your own layout: use the CSS variables from tokens.css (`var(--surface-raised)`, `var(--border)`, `var(--ink-muted)`, `var(--space-4)`, `var(--radius-md)`), never raw colours. Status is always icon + label + colour (`StatusBadge`); `status-critical` is the only colour that asks for action. Sentence case, no emoji.",
  "",
  ...cards.flatMap((c) => {
    const p = propsOf(c.name);
    return [`## ${c.name}`, `_${c.group}_`, "", c.readme, ...(p ? ["", "```ts", p, "```"] : []), ""];
  }),
].join("\n");
writeFileSync(join(PKG, "dist", "COMPONENTS.md"), docs);
console.log(`catalogue: ${cards.length} components → design-system/catalogue.html, dist/COMPONENTS.md`);
